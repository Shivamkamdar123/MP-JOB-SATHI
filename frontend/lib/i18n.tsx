type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: keyof (typeof messages)["en"]) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");
  const [languageLoaded, setLanguageLoaded] = useState(false);
  useEffect(() => {
    const saved = localStorage.getItem("mpjs.language");
    if (saved === "hi" || saved === "en") setLanguageState(saved);
    setLanguageLoaded(true);
  }, []);
  useEffect(() => {
    if (!languageLoaded) return;
    document.documentElement.lang = language;
    localStorage.setItem("mpjs.language", language);
  }, [language, languageLoaded]);
  const setLanguage = useCallback(
    (value: Language) => setLanguageState(value),
    [],
  );
  const t = useCallback(
    (key: keyof (typeof messages)["en"]) => messages[language][key],
    [language],
  );
  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
